package com.nnmedia.read.entity;

public class CDKEYDetialEntity {

    private int type;
    private int monthly_number;
    private int hpoint;
    private String title;
    private String voucher;

    public int getType() {
        return type;
    }

    public void setType(int type) {
        this.type = type;
    }

    public int getMonthly_number() {
        return monthly_number;
    }

    public void setMonthly_number(int monthly_number) {
        this.monthly_number = monthly_number;
    }

    public int getHpoint() {
        return hpoint;
    }

    public void setHpoint(int hpoint) {
        this.hpoint = hpoint;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getVoucher() {
        return voucher;
    }

    public void setVoucher(String voucher) {
        this.voucher = voucher;
    }
}